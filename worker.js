function relatedItemToken(item) {
  if (item.type === "cms") {
    return "cms:" + Number(item.id);
  }

  if (item.type === "static") {
    return "static:" + String(item.key || "");
  }

  return "";
}


function relatedItemReference(item) {
  if (item.type === "cms") {
    return {
      type: "cms",
      id: Number(item.id)
    };
  }

  return {
    type: "static",
    key: item.key
  };
}


function safeRelatedImageUrl(value) {
  if (typeof value !== "string" || !value.trim()) {
    return "";
  }

  try {
    const url = new URL(value, window.location.origin);

    if (url.protocol === "https:" || url.protocol === "http:") {
      return url.href;
    }
  } catch {}

  return "";
}


