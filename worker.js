function parseRelatedItems(value, legacyIds, sourceProductId) {
  if (value === undefined) {
    if (legacyIds === undefined) {
      value = [];
    } else if (Array.isArray(legacyIds)) {
      value = legacyIds.map(id => ({ type: "cms", id }));
    } else {
      return {
        items: [],
        error: "related_items must be an array"
      };
    }
  }

  if (!Array.isArray(value)) {
    return {
      items: [],
      error: "related_items must be an array"
    };
  }

  const items = [];
  const seen = new Set();

  for (const item of value) {
    if (!item || typeof item !== "object" || Array.isArray(item)) {
      return {
        items: [],
        error: "Each related item must be an object"
      };
    }

    if (item.type === "cms") {
      const rawId = item.id;
      const validRawId =
        typeof rawId === "number" ||
        (
          typeof rawId === "string" &&
          /^\d+$/.test(rawId.trim())
        );

      const id = Number(rawId);

      if (!validRawId || !Number.isSafeInteger(id) || id <= 0) {
        return {
          items: [],
          error: "CMS related items must have a valid product ID"
        };
      }

      if (
        sourceProductId !== undefined &&
        id === Number(sourceProductId)
      ) {
        return {
          items: [],
          error: "A product cannot be related to itself"
        };
      }

      const token = "cms:" + id;

      if (!seen.has(token)) {
        seen.add(token);
        items.push({ type: "cms", id });
      }

      continue;
    }

    if (item.type === "static") {
      const key =
        typeof item.key === "string"
          ? item.key
          : "";

      if (!STATIC_PRODUCT_BY_KEY.has(key)) {
        return {
          items: [],
          error: "Static related item was not found"
        };
      }

      const token = "static:" + key;

      if (!seen.has(token)) {
        seen.add(token);
        items.push({ type: "static", key });
      }

      continue;
    }

    return {
      items: [],
      error: "Related item type must be cms or static"
    };
  }

  return { items, error: null };
}


async function validateRelatedItems(db, items, sourceProductId) {
  const cmsIds = items
    .filter(item => item.type === "cms")
    .map(item => item.id);

  if (
    sourceProductId !== undefined &&
    cmsIds.includes(Number(sourceProductId))
  ) {
    return "A product cannot be related to itself";
  }

  if (!cmsIds.length) {
    return null;
  }

  const placeholders =
    cmsIds.map(() => "?").join(", ");

  const { results } = await db
    .prepare(
      "SELECT id FROM products WHERE id IN (" +
      placeholders +
      ")"
    )
    .bind(...cmsIds)
    .all();

  const foundIds =
    new Set(results.map(product => Number(product.id)));

  if (cmsIds.some(id => !foundIds.has(id))) {
    return "One or more related CMS products do not exist";
  }

  return null;
}


function relationReference(row) {
  if (row.related_type === "cms") {
    return {
      type: "cms",
      id: Number(row.related_key)
    };
  }

  return {
    type: "static",
    key: row.related_key
  };
}


function productRelatedStatements(db, productId, items) {
  const statements = [];

  items.forEach((item, position) => {
    const relatedKey =
      item.type === "cms"
        ? String(item.id)
        : item.key;

    statements.push(
      db
        .prepare(
          "INSERT INTO product_related_items " +
          "(product_id, related_type, related_key, position) " +
          "VALUES (?, ?, ?, ?)"
        )
        .bind(productId, item.type, relatedKey, position)
    );

    if (item.type === "cms") {
      statements.push(
        db
          .prepare(
            "INSERT INTO product_related " +
            "(product_id, related_product_id, position) " +
            "VALUES (?, ?, ?)"
          )
          .bind(productId, item.id, position)
      );
    }
  });

  return statements;
}


function firstProductImage(value) {
  let parsed = value;

  if (typeof value === "string") {
    try {
      parsed = JSON.parse(value);
    } catch {
      return value.trim();
    }
  }

  const images = Array.isArray(parsed)
    ? parsed
    : parsed == null
      ? []
      : [parsed];

  for (const image of images) {
    if (typeof image === "string" && image.trim()) {
      return image.trim();
    }

    if (
      image &&
      typeof image === "object" &&
      typeof image.url === "string" &&
      image.url.trim()
    ) {
      return image.url.trim();
    }
  }

  return "";
}


function createSlug(text) {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/ë/g, "e")
    .replace(/ç/g, "c")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}



